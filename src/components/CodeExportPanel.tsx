import React, { useState } from 'react';
import { Copy, Check, Download, Code2 } from 'lucide-react';
import { SoftwareProject } from '../types/builder';

interface CodeExportPanelProps {
  project: SoftwareProject;
}

export function generateProjectTypeScriptCode(project: SoftwareProject): string {
  const vars = project.blocks.filter((b) => b.type === 'variable');
  const buttons = project.blocks.filter((b) => b.type === 'button');
  const conditions = project.blocks.filter((b) => b.type === 'condition');
  const transforms = project.blocks.filter((b) => b.type === 'transform');
  const metrics = project.blocks.filter((b) => b.type === 'metric');
  const alerts = project.blocks.filter((b) => b.type === 'alert');

  const stateLines = vars
    .map(
      (v) =>
        `  const [${v.config.variableName}, set_${v.config.variableName}] = useState<any>(${JSON.stringify(
          v.config.initialValue ?? 0
        )});`
    )
    .join('\n');

  const transformComments = transforms
    .map(
      (t) =>
        `  // Transform Block: ${t.label}\n  const ${t.config.outputVariableName} = Number(${t.config.variableName}) * Number(${
          t.config.secondaryVariableName || t.config.actionValue || 1
        });`
    )
    .join('\n\n');

  const conditionComments = conditions
    .map(
      (c) =>
        `  // Condition Block: ${c.label}\n  const ${c.config.outputVariableName} = ${c.config.variableName} ${c.config.conditionOperator} ${c.config.conditionThreshold};`
    )
    .join('\n\n');

  const buttonHandlers = buttons
    .map((b) => {
      const varName = b.config.variableName || 'state';
      const val = b.config.actionValue ?? 1;
      const op =
        b.config.actionType === 'decrement'
          ? `- ${val}`
          : b.config.actionType === 'multiply'
          ? `* ${val}`
          : `+ ${val}`;
      return `  const handle_${b.id.replace(/[^a-zA-Z0-9]/g, '_')} = () => {\n    set_${varName}((prev: number) => prev ${op});\n  };`;
    })
    .join('\n\n');

  const metricJsx = metrics
    .map(
      (m) =>
        `        <div className="p-4 rounded-lg border border-slate-800 bg-slate-900">\n          <div className="text-xs text-slate-400">${m.label}</div>\n          <div className="text-2xl font-mono font-bold mt-1">{${m.config.variableName}} ${m.config.unit || ''}</div>\n        </div>`
    )
    .join('\n');

  const alertJsx = alerts
    .map(
      (a) =>
        `      {${a.config.variableName} && (\n        <div className="p-4 rounded-lg border border-amber-600 bg-amber-950/40 text-amber-200 text-sm">\n          ${a.config.placeholder || a.label}\n        </div>\n      )}`
    )
    .join('\n');

  return `/**
 * Auto-Generated by CodeBuilder Visual Studio
 * Project: ${project.name} (v${project.version})
 * Generated: ${new Date().toISOString()}
 */
import React, { useState } from 'react';

export default function GeneratedApplication() {
  // 1. State Variables
${stateLines || '  const [count, set_count] = useState(0);'}

  // 2. Derived Transforms
${transformComments || '  // No transforms configured'}

  // 3. Condition Gates
${conditionComments || '  // No conditions configured'}

  // 4. Interactive Event Handlers
${buttonHandlers || '  // No button handlers configured'}

  return (
    <div className="max-w-4xl mx-auto p-6 space-y-6 bg-slate-950 text-slate-100 rounded-xl border border-slate-800">
      <header className="border-b border-slate-800 pb-4">
        <h1 className="text-xl font-bold">${project.name}</h1>
        <p className="text-xs text-slate-400 mt-1">${project.description}</p>
      </header>

      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
${metricJsx}
      </div>

${alertJsx}
    </div>
  );
}
`;
}

export const CodeExportPanel: React.FC<CodeExportPanelProps> = ({ project }) => {
  const [copied, setCopied] = useState(false);
  const generatedCode = generateProjectTypeScriptCode(project);

  const handleCopy = () => {
    navigator.clipboard.writeText(generatedCode);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([generatedCode], { type: 'text/typescript;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${project.id}.tsx`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-5">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-800">
        <div>
          <h2 className="text-xl font-semibold text-slate-100">
            Generated TypeScript / React Source Code
          </h2>
          <p className="text-xs text-slate-400 mt-1">
            Compiled live from your {project.blocks.length} visual blocks in &ldquo;{project.name}&rdquo;
          </p>
        </div>

        <div className="flex items-center gap-3 shrink-0">
          <button
            type="button"
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-slate-200 bg-slate-800 border border-slate-700 rounded-lg hover:bg-slate-700 transition-colors whitespace-nowrap shrink-0"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span>Copied Source</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Code</span>
              </>
            )}
          </button>

          <button
            type="button"
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-slate-950 bg-sky-400 rounded-lg hover:bg-sky-300 transition-colors whitespace-nowrap shrink-0"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download .tsx</span>
          </button>
        </div>
      </div>

      <div className="rounded-xl bg-[#0F172A] border border-slate-800 overflow-hidden">
        <div className="px-4 py-2.5 bg-[#0B0F19] border-b border-slate-800 flex items-center justify-between text-xs font-mono text-slate-400">
          <span className="flex items-center gap-2">
            <Code2 className="w-4 h-4 text-sky-400" />
            <span>{project.id}.tsx</span>
          </span>
          <span className="tabular-nums">{generatedCode.split('\n').length} lines</span>
        </div>
        <pre className="p-5 text-xs font-mono text-slate-200 overflow-x-auto leading-relaxed">
          <code>{generatedCode}</code>
        </pre>
      </div>
    </div>
  );
};
